def generate_fraud(rng):
    # 指代型行动指令：不给出真实链接/号码，而是"链接发你了/打这个号码/转这个卡"
    # 让模型学会识别口语化、指代型的可疑行动，而不只是匹配 <URL>/具体号码
    reference_acts = [
        '链接我发你了，点进去按提示操作',
        '链接我稍后发你，点开填写信息就行',
        '电话发你了，拨打这个号码办理',
        '卡号我发你了，把钱转到这个卡上',
        '二维码发你了，扫码操作',
        '账号发你了，加上好友我带你',
        '我把码发你，扫这个码完成操作',
        '号码发你了，打这个电话就行',
    ]
    rows = []
    for cat, spec in FRAUD.items():
        seen = set()
        attempts = 0
        target = FRAUD_PER_CATEGORY
        while len(seen) < target and attempts < target * 40:
            attempts += 1
            if rng.random() < 0.45 and spec.get('full'):
                # 完整模板 + 可能追加施压/行动
                parts = [rng.choice(spec['full'])]
                if rng.random() < 0.35:
                    parts.append(rng.choice(spec['urge']))
                if rng.random() < 0.25:
                    parts.append(rng.choice(spec['act']))
            else:
                # 组件组合；约 22% 使用指代型行动指令
                parts = [rng.choice(spec['open']), rng.choice(spec['body'])]
                if rng.random() < 0.6:
                    parts.append(rng.choice(spec['urge']))
                act = rng.choice(reference_acts) if rng.random() < 0.22 \
                    else rng.choice(spec['act'])
                parts.append(act)
            text = '，'.join(parts)
            text = fill_slots(text, rng)
            seen.add(text)
        rows.extend([(t, 1) for t in seen])
        print(f'  诈骗-{cat}: {len(seen)} 条')
    return rows


NORMAL_PREFIX = [
    '', '', '', '对了，', '哎，', '那个，', '跟你说，', '嘿，',
    '在吗，', '刚看到，', '差点忘了，', '通知一下，',
]
NORMAL_SUFFIX = ['', '', '', '哈', '呀', '哦', '呢', '啊', '哈～', '别忘了哈']


def normal_variant(template, rng):
    """在不改变语义的前提下加口语化前后缀"""
    text = rng.choice(NORMAL_PREFIX) + template
    suffix = rng.choice(NORMAL_SUFFIX)
    if suffix and not text.endswith(suffix):
        text += suffix
    return text


def generate_normal(rng):
    rows = []
    for cat, templates in NORMAL.items():
        seen = set()
        attempts = 0
        target = NORMAL_PER_CATEGORY
        while len(seen) < target and attempts < target * 40:
            attempts += 1
            text = normal_variant(rng.choice(templates), rng)
            text = fill_slots(text, rng)
            seen.add(text)
        rows.extend([(t, 0) for t in seen])
        print(f'  正常-{cat}: {len(seen)} 条')
    return rows


def main():
    print('=' * 55)
    print('多类型话术合成数据生成')
    print('=' * 55)
    rng = random.Random(20260923)

    print('\n[1/2] 生成诈骗话术...')
    fraud_rows = generate_fraud(rng)

    print('\n[2/2] 生成正常话术...')
    normal_rows = generate_normal(rng)

