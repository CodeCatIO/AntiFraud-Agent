def money_small(rng):
    return str(rng.randint(20, 900)) + '元'

def money_big(rng):
    n = rng.randint(2, 80)
    return f'{n}万元'

def money_any(rng):
    return rng.choice([money_small, money_big])(rng)

def digit_str(rng, lo, hi):
    return ''.join(str(rng.randint(0, 9)) for _ in range(rng.randint(lo, hi)))

def slot_url(rng):
    kinds = [
        lambda: 'http://' + digit_str(rng, 1, 1) + 'y' + rng.choice(['cn', 'com']) + '/' + digit_str(rng, 4, 6),
        lambda: 't.cn/' + rng.choice('ABCDEFabcdef') + digit_str(rng, 4, 5),
        lambda: 'dwz.cn/' + digit_str(rng, 5, 6),
        lambda: 'www.' + rng.choice(['vip', 'h5', 'm']) + digit_str(rng, 3, 5) + '.com',
    ]
    return rng.choice(kinds)()

def slot_qq(rng):
    return rng.choice(['QQ', 'qq', '企鹅号']) + digit_str(rng, 6, 10)

def slot_wx(rng):
    return rng.choice(['微信', 'VX', 'vx']) + rng.choice(['：', ':']) + \
           rng.choice(['kf', 'vip', 'hr', 'tz', 'a']) + digit_str(rng, 4, 7)

def slot_phone(rng):
    pre = rng.choice(['400', '010', '021', '0571'])
    return pre + digit_str(rng, 7, 8) if pre == '400' else pre + digit_str(rng, 8, 8)

def slot_app(rng):
    return rng.choice(['会议', '办公', '畅联', '速达', '云信', '有信', '连信']) + \
           rng.choice(['APP', 'app', '软件'])

def slot_bank(rng):
    return rng.choice(['工商银行', '建设银行', '农业银行', '中国银行', '交通银行',
                       '招商银行', '邮储银行', '浦发银行', '民生银行'])

def slot_platform(rng):
    return rng.choice(['淘宝', '天猫', '京东', '拼多多', '抖音', '快手', '美团', '唯品会'])

def slot_code(rng):
    return digit_str(rng, 4, 6)

def slot_cardtail(rng):
    return digit_str(rng, 4, 4)

def slot_time(rng):
    return rng.choice(['一小时内', '今天之内', '24小时内', '下班前', '马上', '尽快',
                       '上午十点前', '今天24点前'])

def fill_slots(text, rng):
    """替换模板中的槽位标记"""
    table = {
        '{url}': lambda: slot_url(rng),
        '{qq}': lambda: slot_qq(rng),
        '{wx}': lambda: slot_wx(rng),
        '{phone}': lambda: slot_phone(rng),
        '{app}': lambda: slot_app(rng),
        '{bank}': lambda: slot_bank(rng),
        '{platform}': lambda: slot_platform(rng),
        '{code}': lambda: slot_code(rng),
        '#small': lambda: money_small(rng),
        '#big': lambda: money_big(rng),
        '#any': lambda: money_any(rng),
        '{tail}': lambda: slot_cardtail(rng),
        '{time}': lambda: slot_time(rng),
    }
    for k, fn in table.items():
        while k in text:
            text = text.replace(k, fn(), 1)
    return text


